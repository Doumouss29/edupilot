"""Regression tests for administrative privilege boundaries (disposable SQLite only)."""
import os,sys,tempfile,unittest
from pathlib import Path
from werkzeug.security import generate_password_hash

ROOT=Path(__file__).resolve().parents[1]
TEMP=tempfile.TemporaryDirectory()
os.environ['DB_ENGINE']='sqlite'
os.environ['DATABASE_PATH']=str(Path(TEMP.name)/'boot.db')
os.environ['SECRET_KEY']='admin-permission-tests'
sys.path.insert(0,str(ROOT))
import app as project

class AdministrationPermissionsTests(unittest.TestCase):
    def setUp(self):
        project.DB=str(Path(TEMP.name)/(self._testMethodName+'.db'))
        with project.db() as c:
            c.executescript(project.SCHEMA)
            c.execute("ALTER TABLE years ADD COLUMN status TEXT NOT NULL DEFAULT 'active'")
            c.execute("ALTER TABLE classes ADD COLUMN filiere_id INTEGER")
            c.execute("CREATE TABLE IF NOT EXISTS filieres(id INTEGER PRIMARY KEY,school_id INTEGER,name TEXT)")
            c.execute("INSERT INTO schools(id,name,slug) VALUES (1,'School A','school-a'),(2,'School B','school-b')")
            c.execute("INSERT INTO years(id,school_id,label,is_active,status) VALUES (1,1,'2026-2027',1,'active'),(2,2,'2026-2027',1,'active')")
            c.execute("INSERT INTO classes(id,school_id,year_id,name) VALUES (1,1,1,'Class A'),(2,2,2,'Class B')")
            for uid,sid,role in [(1,1,'administratif'),(2,1,'admin'),(3,1,'enseignant'),
                                 (4,1,'etudiant'),(5,2,'admin'),(6,1,'administratif'),(7,1,'parent')]:
                c.execute("""INSERT INTO users(id,school_id,name,email,password_hash,role) VALUES (?,?,?,?,?,?)""",
                    (uid,sid,role,f'u{uid}@test.invalid',generate_password_hash('PasswordTest123'),role))
        self.client=project.app.test_client()

    def actor(self,uid):
        u=project.one('SELECT * FROM users WHERE id=?',(uid,))
        with self.client.session_transaction() as s:
            s.clear()
            s['uid']=uid
            s['auth_stamp']=project.session_auth_stamp(u)
            s['csrf']='csrf'

    def post(self,url,**values):
        return self.client.post(url,data={'csrf':'csrf',**values})

    def test_administrative_cannot_create_another_administrative(self):
        self.actor(1)
        r=self.post('/people',role='administratif',name='Other',email='new@test.invalid')
        self.assertEqual(r.status_code,403)
        self.assertIsNone(project.one("SELECT id FROM users WHERE email='new@test.invalid'"))

    def test_administrative_cannot_edit_school_admin(self):
        self.actor(1)
        self.assertEqual(self.client.get('/people/2/edit').status_code,403)
        self.assertEqual(self.post('/people/2/edit',name='Renamed',email='u2@test.invalid').status_code,403)

    def test_administrative_cannot_edit_peer_administrative(self):
        self.actor(1)
        self.assertEqual(self.post('/people/6/edit',name='Changed',email='u6@test.invalid').status_code,403)

    def test_admin_cannot_edit_admin_account(self):
        self.actor(2)
        self.assertEqual(self.post('/people/2/edit',name='Changed',email='u2@test.invalid').status_code,403)

    def test_administrative_cannot_suspend_admin_in_bulk(self):
        self.actor(1)
        self.assertIn(self.post('/people/bulk',action='suspend',user_ids=['2']).status_code,(302,403))
        self.assertEqual(project.one('SELECT active FROM users WHERE id=2')['active'],1)

    def test_administrative_cannot_suspend_administrative_peer(self):
        self.actor(1)
        self.assertIn(self.post('/people/bulk',action='suspend',user_ids=['6']).status_code,(302,403))
        self.assertEqual(project.one('SELECT active FROM users WHERE id=6')['active'],1)

    def test_administrative_cannot_send_admin_invite(self):
        self.actor(1)
        self.assertEqual(self.post('/accounts/2/resend-invite').status_code,403)

    def test_cross_school_user_cannot_be_edited(self):
        self.actor(2)
        self.assertEqual(self.post('/people/5/edit',name='Other',email='u5@test.invalid').status_code,404)

    def test_role_change_invalidates_existing_session(self):
        self.actor(6)
        with project.db() as c:
            c.execute("UPDATE users SET role='admin' WHERE id=6")
        self.client.get('/health')
        with self.client.session_transaction() as s:
            self.assertNotIn('uid',s)

    def test_email_change_invalidates_existing_session(self):
        self.actor(6)
        with project.db() as c:
            c.execute("UPDATE users SET email='changed@test.invalid' WHERE id=6")
        self.client.get('/health')
        with self.client.session_transaction() as s:
            self.assertNotIn('uid',s)

    def test_admin_can_create_administrative(self):
        self.actor(2)
        # Required fields such as matricule are generated by the application.
        r=self.post('/people',role='administratif',name='New Staff',email='staff@test.invalid')
        self.assertEqual(r.status_code,302)
        self.assertIsNotNone(project.one("SELECT id FROM users WHERE email='staff@test.invalid'"))

if __name__=='__main__':
    unittest.main()
